def specs(family, machine_type):
    "Return a machine type's specs in the shape instances.json uses"
    cores, memory, local_ssd, benchmark, network_egress = MACHINE_TYPES[family][
        machine_type
    ]
    values = {
        **FAMILY_SPECS[family],
        "cores": cores,
        "memory": memory,
        "local_ssd": local_ssd,
        "benchmark": benchmark,
        "network_egress": network_egress,
        **SPEC_OVERRIDES.get(machine_type, {}),
    }
    return {key: values[key] for key in SPEC_KEYS if values.get(key) is not None}
